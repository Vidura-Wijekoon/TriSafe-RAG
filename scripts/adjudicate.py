"""Adjudication of the answers B1 actually delivered.

Alias matching (Sec. metrics) is the automatic correctness criterion of the
paper.  It can be wrong in both directions: a verbose reply that happens to
contain the right number is scored correct, and a correct reply in a spelling
missing from the alias list is scored wrong.  This kit lists every answer the
vanilla system delivered on the test split and records a human / assistant
judgement next to the alias label, so that the error of the automatic
criterion is itself a reported number.

    python scripts/adjudicate.py make  --backend neural7b --seed 0   # -> data/benchmark/adjudication_B1_delivered.csv
    python scripts/adjudicate.py print --backend neural7b --seed 0   # compact listing for labelling
    python scripts/adjudicate.py stats                               # -> paper/trust2027/generated/adjudication.tex

Sheet columns: id, language, gold_answerable, query, gold_aliases, draft_text,
alias_match (0/1, automatic), adjudicated (correct | wrong | partial, filled by
the reviewer), reviewer, notes.  ``partial`` = the right value is present but
attributed or explained wrongly; it is counted as *wrong* in the strict
comparison and as *correct* in the lenient one.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SHEET = ROOT / "data" / "benchmark" / "adjudication_B1_delivered.csv"
OUT = ROOT / "paper" / "trust2027" / "generated" / "adjudication.tex"
FIELDS = ["id", "language", "gold_answerable", "query", "gold_aliases", "draft_text", "alias_match",
          "adjudicated", "reviewer", "notes"]


def delivered(backend: str, seed: int) -> list[dict]:
    from src.eval.benchmark import draft_correct, normalise_draft
    test_ids = set(json.loads((ROOT / "data" / "benchmark" / "split.json").read_text(encoding="utf-8"))["test"])
    p = ROOT / "results" / backend / f"drafts_seed{seed}.jsonl"
    rows = []
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        d = json.loads(line)
        normalise_draft(d)
        if d["id"] not in test_ids or d["model_abstained"] or not d["hits"]:
            continue  # B1 delivers exactly the drafts the generator did not abstain on
        rows.append({
            "id": d["id"], "language": d["language"], "gold_answerable": int(d["gold_answerable"]),
            "query": d["query"], "gold_aliases": " | ".join(d["gold_answers"]),
            "draft_text": " ".join((d["draft_text"] or "").split()),
            "alias_match": draft_correct(d) if int(d["gold_answerable"]) == 1 else 0,
            "adjudicated": "", "reviewer": "", "notes": "",
        })
    return rows


def make(args) -> None:
    rows = delivered(args.backend, args.seed)
    if SHEET.exists() and not args.force:
        old = {r["id"]: r for r in csv.DictReader(SHEET.open(encoding="utf-8-sig", newline=""))}
        for r in rows:
            if r["id"] in old:
                for k in ("adjudicated", "reviewer", "notes"):
                    r[k] = old[r["id"]].get(k, "")
    with SHEET.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {SHEET.relative_to(ROOT)}: {len(rows)} delivered answers "
          f"({Counter(r['language'] for r in rows)}); alias-correct: {sum(r['alias_match'] for r in rows)}")


def print_rows(args) -> None:
    rows = delivered(args.backend, args.seed)
    for r in rows:
        print(f"{r['id']} [{r['language']}] ans={r['gold_answerable']} alias={r['alias_match']}\n"
              f"  Q: {r['query'][:160]}\n  G: {r['gold_aliases'][:160]}\n  D: {r['draft_text'][:420]}")


def stats(args) -> None:
    rows = list(csv.DictReader(SHEET.open(encoding="utf-8-sig", newline="")))
    done = [r for r in rows if (r.get("adjudicated") or "").strip()]
    lines = ["%% auto-generated by scripts/adjudicate.py stats; do not edit"]
    if not done:
        lines.append(r"\newcommand{\LAdjN}{0}")
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("no adjudications yet")
        return
    for r in done:
        v = r["adjudicated"].strip().lower()
        if v not in ("correct", "wrong", "partial"):
            raise SystemExit(f"{r['id']}: adjudicated must be correct|wrong|partial, got {v!r}")
    ans = [r for r in done if r["gold_answerable"] == "1"]
    unans = [r for r in done if r["gold_answerable"] == "0"]
    alias = [int(r["alias_match"]) for r in ans]
    strict = [int(r["adjudicated"].strip().lower() == "correct") for r in ans]
    lenient = [int(r["adjudicated"].strip().lower() in ("correct", "partial")) for r in ans]
    fp = sum(1 for a, s in zip(alias, strict) if a == 1 and s == 0)     # alias says right, reviewer says wrong
    fn = sum(1 for a, s in zip(alias, strict) if a == 0 and s == 1)     # alias says wrong, reviewer says right
    fp_len = sum(1 for a, s in zip(alias, lenient) if a == 1 and s == 0)
    fn_len = sum(1 for a, s in zip(alias, lenient) if a == 0 and s == 1)
    partial = sum(1 for r in ans if r["adjudicated"].strip().lower() == "partial")
    by_lang = Counter(r["language"] for r in done)
    fp_lang = Counter(r["language"] for r in ans if int(r["alias_match"]) == 1 and r["adjudicated"].strip().lower() != "correct")

    def m(name, val):
        lines.append(rf"\newcommand{{\LAdj{name}}}{{{val}}}")

    m("N", len(done)); m("NAns", len(ans)); m("NUnans", len(unans))
    m("AliasCorrect", sum(alias)); m("StrictCorrect", sum(strict)); m("LenientCorrect", sum(lenient)); m("Partial", partial)
    m("FP", fp); m("FN", fn); m("FPLenient", fp_len); m("FNLenient", fn_len)
    m("AgreeStrict", f"{100 * sum(1 for a, s in zip(alias, strict) if a == s) / max(len(ans), 1):.0f}")
    m("AgreeLenient", f"{100 * sum(1 for a, s in zip(alias, lenient) if a == s) / max(len(ans), 1):.0f}")
    m("AliasAcc", f"{sum(alias) / max(len(ans), 1):.3f}"); m("StrictAcc", f"{sum(strict) / max(len(ans), 1):.3f}")
    m("LenientAcc", f"{sum(lenient) / max(len(ans), 1):.3f}")
    for l in ("en", "si", "ta", "mixed"):
        m(f"N{l}", by_lang.get(l, 0)); m(f"FP{l}", fp_lang.get(l, 0))
    empty = sum(1 for r in done if "citation-only" in (r.get("notes") or ""))
    m("Empty", empty)
    m("EmptyNonEn", sum(1 for r in done if "citation-only" in (r.get("notes") or "") and r["language"] != "en"))
    m("WrongLang", sum(1 for r in done if "Chinese" in (r.get("notes") or "")))
    for l in ("en", "si", "ta", "mixed"):
        m(f"Empty{l}", sum(1 for r in done if "citation-only" in (r.get("notes") or "") and r["language"] == l))
        m(f"Strict{l}", sum(1 for r in done if r["language"] == l and r["adjudicated"].strip().lower() == "correct"))
    m("Reviewers", ", ".join(sorted({(r.get("reviewer") or "").strip() for r in done if (r.get("reviewer") or "").strip()})) or "--")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"adjudicated {len(done)}/{len(rows)}: answerable {len(ans)}: alias {sum(alias)} / strict {sum(strict)} / lenient {sum(lenient)}; "
          f"alias false positives {fp} (lenient {fp_len}), false negatives {fn} (lenient {fn_len}); partial {partial}; unanswerable delivered {len(unans)}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("make", "print"):
        s = sub.add_parser(name)
        s.add_argument("--backend", default="neural7b")
        s.add_argument("--seed", type=int, default=0)
        s.add_argument("--force", action="store_true")
    sub.add_parser("stats")
    args = ap.parse_args()
    {"make": make, "print": print_rows, "stats": stats}[args.cmd](args)


if __name__ == "__main__":
    main()
